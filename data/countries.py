NAMES: list[str] = [name for _flag, name in COUNTRIES]
_FLAGS = {name: flag for flag, name in COUNTRIES}


def flag_for(name: str | None) -> str:
    """Drapeau d'un pays (🌍 si inconnu)."""
    return _FLAGS.get((name or "").strip(), "🌍")


def label_for(name: str | None) -> str:
    """« 🇲🇦 Maroc » — prêt à afficher."""
    clean = (name or "").strip()
    if not clean:
        return "🌍 Pays non précisé"
    return f"{flag_for(clean)} {clean}"


def index_of(name: str | None, default: int = 0) -> int:
    """Position d'un pays dans la liste (0 par défaut)."""
    try:
        return NAMES.index((name or "").strip())
    except ValueError:
        return default
